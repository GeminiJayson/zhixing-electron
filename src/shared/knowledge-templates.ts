/** 换行符常量：模板里用 join(NL) 而不是在字符串里写转义，读起来更清楚。 */
const NL = '\n'

/**
 * 知识条目的正文模板。设计见 docs/specs/knowledge-base-reorg.md §6。
 *
 * 只有三类给固定结构，因为它们填起来容易漏项：
 *   概念   —— 最容易漏「它不是什么」，于是望文生义；
 *   方法论 —— 最容易漏「什么时候别用」，于是到处硬套；
 *   踩坑   —— 价值全在排查过程，而人天然只想写结论。
 *
 * 另外五类（摘要 / 综合分析 / 输出 / 笔记 / 项目记录）用自由格式 ——
 * 它们本来就没什么固定结构，强加模板只会让人先删一遍。
 */

export const KNOWLEDGE_TEMPLATES: Record<string, string> = {
  concept: [
    '## 定义（我自己的话）',
    '',
    '',
    '## 它不是什么（边界）',
    '',
    '<!-- 防止望文生义：写出容易和它混淆的东西，以及区别在哪 -->',
    '',
    '## 来源',
    '',
    '<!-- 用徽标面板里的「来源」挂上原始资料；没有来源就只能是待确认 -->',
    '',
    '## 相关概念',
    '',
  ].join(NL),

  method: [
    '## 什么时候用它（场景）',
    '',
    '',
    '## 什么时候别用（反场景）',
    '',
    '<!-- 最容易漏的一节。写不出反场景，往往说明还没真正理解它 -->',
    '',
    '## 步骤',
    '',
    '1. ',
    '',
    '## 前置条件 / 需要的东西',
    '',
    '',
    '## 失败的样子',
    '',
    '<!-- 做错了会怎样。知道失败长什么样，才能在过程中及时发现 -->',
    '',
  ].join(NL),

  pitfall: [
    '## 现象',
    '',
    '<!-- 当时看到什么。别写「报错了」，写具体的表现 -->',
    '',
    '## 排查过程',
    '',
    '<!-- 试过什么、排除掉什么、为什么排除。这一节最值钱 —— 现象和结论网上都有，只有排查路径是你自己的 -->',
    '',
    '## 根因',
    '',
    '',
    '## 修复',
    '',
    '',
    '## 下次怎么避免',
    '',
    '<!-- 要可执行。「下次小心点」不算 -->',
    '',
  ].join(NL),
}

export function templateFor(kind: string): string | null {
  return KNOWLEDGE_TEMPLATES[kind] ?? null
}
